#!/usr/bin/env python3
"""Generate src/unicode_tables.rs by asking gawk under C.UTF-8.

usage: tools/gen_unicode_tables.py [--gawk PATH] [--check] [--pyawk DIR]

hawk's UTF-8 mode takes its character classes (`[[:alpha:]]` and the rest)
and toupper/tolower from gawk, as pyawk v1.1 does: gawk in turn takes them
from the C library's C.UTF-8 locale.  Rather than guess with another
Unicode library, we ask gawk about every code point and store its answers.

How: write every Unicode scalar value (except newline and the surrogates,
which are not characters) one per line, then have gawk report, for each
line, which classes it matches and what toupper/tolower make of it.  The
result is a Rust module of sorted range tables.

--check compares a fresh run with the committed file instead of writing.
--pyawk DIR also checks the tables are the same as pyawk v1.1's
(DIR/pyawk/unicode_tables.py), which came from GNU Awk 5.4.1.

The gawk used is $HAWK_REF_GAWK, else /workspace/refs/local/bin/gawk if
it exists, else "gawk" on PATH.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "unicode_tables.rs"

CLASSES = ["alpha", "digit", "alnum", "upper", "lower", "space", "blank", "punct", "xdigit", "cntrl", "print", "graph"]
LETTERS = dict(zip("adnulsbpxcrg", CLASSES))
CODE_POINTS = [c for c in range(0x110000) if c != 10 and not 0xD800 <= c <= 0xDFFF]

GAWK_PROGRAM = r"""
{
    f = ""
    if ($0 ~ /^[[:alpha:]]$/)  f = f "a"
    if ($0 ~ /^[[:digit:]]$/)  f = f "d"
    if ($0 ~ /^[[:alnum:]]$/)  f = f "n"
    if ($0 ~ /^[[:upper:]]$/)  f = f "u"
    if ($0 ~ /^[[:lower:]]$/)  f = f "l"
    if ($0 ~ /^[[:space:]]$/)  f = f "s"
    if ($0 ~ /^[[:blank:]]$/)  f = f "b"
    if ($0 ~ /^[[:punct:]]$/)  f = f "p"
    if ($0 ~ /^[[:xdigit:]]$/) f = f "x"
    if ($0 ~ /^[[:cntrl:]]$/)  f = f "c"
    if ($0 ~ /^[[:print:]]$/)  f = f "r"
    if ($0 ~ /^[[:graph:]]$/)  f = f "g"
    print f > FLAGS
    print toupper($0) > UPPER
    print tolower($0) > LOWER
}
"""


def ranges(cps):
    """Sorted code points -> (first, last) runs of consecutive values."""
    out = []
    for c in cps:
        if out and c == out[-1][1] + 1:
            out[-1] = (out[-1][0], c)
        else:
            out.append((c, c))
    return out


def case_runs(mapping):
    """A code-point mapping as (first, last, step, delta) runs: first,
    first+step, ..., last each map to themselves plus delta (pyawk's
    compression, so the two can be compared run for run)."""
    out = []
    for c in sorted(mapping):
        d = mapping[c] - c
        if out:
            first, last, step, delta = out[-1]
            if delta == d and (c - last == step or (first == last and c - last <= 2)):
                out[-1] = [first, c, c - last if first == last else step, d]
                continue
        out.append([c, c, 1, d])
    return [tuple(r) for r in out]


def ask_gawk(gawk):
    with tempfile.TemporaryDirectory() as tmp:
        t = Path(tmp)
        (t / "in").write_bytes(b"".join(chr(c).encode("utf-8") + b"\n" for c in CODE_POINTS))
        env = dict(os.environ, LC_ALL="C.UTF-8")
        outputs = [f"-v{name}={t}/{name.lower()}" for name in ("FLAGS", "UPPER", "LOWER")]
        subprocess.run([gawk, *outputs, GAWK_PROGRAM, str(t / "in")], env=env, check=True)
        flags = (t / "flags").read_bytes().split(b"\n")[:-1]
        upper = (t / "upper").read_bytes().split(b"\n")[:-1]
        lower = (t / "lower").read_bytes().split(b"\n")[:-1]
        version = subprocess.run([gawk, "--version"], capture_output=True, encoding="utf-8",
                                 errors="replace").stdout.splitlines()[0]
    assert len(flags) == len(upper) == len(lower) == len(CODE_POINTS), "gawk output out of step"
    members = {name: [] for name in CLASSES}
    for c, f in zip(CODE_POINTS, flags):
        for letter in f.decode():
            members[LETTERS[letter]].append(c)
    # "\n" (left out above) is a space and a control character.
    for name in ("space", "cntrl"):
        members[name] = sorted(members[name] + [10])

    def mapping(lines):
        out = {}
        for c, line in zip(CODE_POINTS, lines):
            s = line.decode("utf-8")
            assert len(s) == 1, f"U+{c:04X} maps to {len(s)} characters"
            if ord(s) != c:
                out[c] = ord(s)
        return out

    return members, mapping(upper), mapping(lower), version


def render(members, upper, lower, version):
    lines = [
        "//! Unicode character classes and case mappings for UTF-8 mode.",
        "//!",
        "//! GENERATED by tools/gen_unicode_tables.py -- do not edit by hand.",
        f"//! Source: {version}, LC_ALL=C.UTF-8 (in effect, the C library's tables).",
        "//!",
        "//! Each class is a sorted list of non-overlapping (first, last)",
        "//! code-point ranges.  UPPER and LOWER are (first, last, step, delta)",
        "//! runs: each code point first, first+step, ..., last maps to itself",
        "//! plus delta.  Both are searched by binary search.",
        "",
        "#[rustfmt::skip]",
        "pub const CLASSES: &[(&str, &[(u32, u32)])] = &[",
    ]
    for name in CLASSES:
        rs = ranges(members[name])
        lines.append(f"    (\"{name}\", &[")
        for i in range(0, len(rs), 6):
            lines.append("        " + " ".join(f"(0x{a:X}, 0x{b:X})," for a, b in rs[i:i + 6]))
        lines.append("    ]),")
    lines.append("];")
    for title, mp in (("UPPER", upper), ("LOWER", lower)):
        lines.append("")
        lines.append("#[rustfmt::skip]")
        lines.append(f"pub const {title}: &[(u32, u32, u32, i32)] = &[")
        runs = case_runs(mp)
        for i in range(0, len(runs), 4):
            lines.append("    " + " ".join(f"(0x{a:X}, 0x{b:X}, {s}, {d})," for a, b, s, d in runs[i:i + 4]))
        lines.append("];")
    return "\n".join(lines) + "\n"


def same_as_pyawk(members, upper, lower, pyawk_dir):
    ns = {}
    exec((Path(pyawk_dir) / "pyawk" / "unicode_tables.py").read_text(encoding="utf-8"), ns)
    ok = True
    for name in CLASSES:
        if tuple(ranges(members[name])) != tuple(ns["CLASSES"][name]):
            print(f"class {name} differs from pyawk's"); ok = False
    if tuple(case_runs(upper)) != ns["UPPER"]:
        print("UPPER differs from pyawk's"); ok = False
    if tuple(case_runs(lower)) != ns["LOWER"]:
        print("LOWER differs from pyawk's"); ok = False
    return ok


def default_gawk():
    if os.environ.get("HAWK_REF_GAWK"):
        return os.environ["HAWK_REF_GAWK"]
    local = Path("/workspace/refs/local/bin/gawk")
    return str(local) if local.exists() else "gawk"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--gawk", default=None)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--pyawk", default=None, help="a pyawk v1.1 checkout to compare with")
    args = ap.parse_args(argv)
    gawk = args.gawk or default_gawk()
    try:
        data = ask_gawk(gawk)
    except (OSError, subprocess.CalledProcessError) as exc:
        print(f"gen_unicode_tables: cannot run {gawk}: {exc}", file=sys.stderr)
        return 2
    if args.pyawk and not same_as_pyawk(*data[:3], args.pyawk):
        return 1
    text = render(*data)
    if args.check:
        same = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("unicode_tables.rs is up to date" if same else "unicode_tables.rs differs from a fresh run")
        return 0 if same else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
